def _xtime(a): return ((a<<1) ^ 0x1B) & 0xFF if a & 0x80 else (a<<1)
def _mul(a,b):
    r=0
    for _ in range(8):
        if b&1: r^=a
        hi=a&0x80; a=(a<<1)&0xFF
        if hi: a^=0x1B
        b>>=1
    return r

RCON=[0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36]

def key_expansion(key):
    assert len(key)==16
    w=[list(key[4*i:4*i+4]) for i in range(4)]
    for i in range(4,44):
        t=list(w[i-1])
        if i%4==0:
            t=t[1:]+t[:1]
            t=[SBOX[b] for b in t]
            t[0]^=RCON[i//4-1]
        w.append([w[i-4][j]^t[j] for j in range(4)])
    return w  # 44 words

def _add_round_key(s,w,r):
    for c in range(4):
        for row in range(4):
            s[row][c]^=w[r*4+c][row]

def _sub_bytes(s):
    for r in range(4):
        for c in range(4): s[r][c]=SBOX[s[r][c]]

def _shift_rows(s):
    for r in range(1,4):
        s[r]=s[r][r:]+s[r][:r]

def _mix_columns(s):
    for c in range(4):
        a=[s[r][c] for r in range(4)]
        s[0][c]=_mul(a[0],2)^_mul(a[1],3)^a[2]^a[3]
        s[1][c]=a[0]^_mul(a[1],2)^_mul(a[2],3)^a[3]
        s[2][c]=a[0]^a[1]^_mul(a[2],2)^_mul(a[3],3)
        s[3][c]=_mul(a[0],3)^a[1]^a[2]^_mul(a[3],2)

def encrypt_block(key, pt):
    w=key_expansion(key)
    s=[[pt[r+4*c] for c in range(4)] for r in range(4)]
    _add_round_key(s,w,0)
    for rnd in range(1,10):
        _sub_bytes(s); _shift_rows(s); _mix_columns(s); _add_round_key(s,w,rnd)
    _sub_bytes(s); _shift_rows(s); _add_round_key(s,w,10)
    return bytes(s[r][c] for c in range(4) for r in range(4))

def _lshift(b):
    out=bytearray(16); carry=0
    for i in range(15,-1,-1):
        out[i]=((b[i]<<1)|carry)&0xFF; carry=(b[i]>>7)&1
    return bytes(out), carry

def cmac(key, msg):
    L=encrypt_block(key, b"\x00"*16)
    K1,c=_lshift(L)
    if c: K1=bytes(x^y for x,y in zip(K1, b"\x00"*15+b"\x87"))
    K2,c=_lshift(K1)
    if c: K2=bytes(x^y for x,y in zip(K2, b"\x00"*15+b"\x87"))
    n=(len(msg)+15)//16
    if n==0:
        n=1; complete=False
    else:
        complete=(len(msg)%16==0)
    if complete:
        last=bytes(x^y for x,y in zip(msg[16*(n-1):], K1))
    else:
        rem=msg[16*(n-1):]; pad=rem+b"\x80"+b"\x00"*(15-len(rem))
        last=bytes(x^y for x,y in zip(pad, K2))
    x=b"\x00"*16
    for i in range(n-1):
        blk=msg[16*i:16*i+16]
        x=encrypt_block(key, bytes(a^b for a,b in zip(x,blk)))
    return encrypt_block(key, bytes(a^b for a,b in zip(x,last)))
